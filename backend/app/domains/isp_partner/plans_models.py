"""Phase 2a tables (ADDENDUM_02): speed groups, packages, coupon batches,
subscribers. New tables only; FKs point into the existing ``queue_profiles``,
``voucher_plans``, ``voucher_batches``, ``vouchers`` and ``guests`` tables,
which are not altered.

A coupon IS an existing ``Voucher`` (generated by ``VoucherService``). A
coupon batch above 1000 codes is several voucher batches, recorded as
``isp_coupon_batch_parts`` rows (one per voucher batch). Serials are derived
(``<prefix>-<batch seq>-<n>``, n by code order within the batch), so no
per-code table is needed.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    SmallInteger,
    String,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.database.base import BaseModel


def _fk(target: str, *, nullable: bool = False, ondelete: str | None = None):  # noqa: ANN202
    return mapped_column(
        UUID(as_uuid=True), ForeignKey(target, ondelete=ondelete), nullable=nullable
    )


DEFAULT_REMINDER_OPT_IN = {"email": True, "sms": False, "whatsapp": False}


class IspPlanSettings(BaseModel):
    __tablename__ = "isp_plan_settings"

    isp_organization_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("organizations.id"), nullable=False, unique=True
    )
    default_validity_days: Mapped[int] = mapped_column(
        Integer, nullable=False, default=30, server_default="30"
    )


class IspSpeedGroup(BaseModel):
    __tablename__ = "isp_speed_groups"

    isp_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    name: Mapped[str] = mapped_column(String(100), nullable=False)
    download_kbps: Mapped[int] = mapped_column(Integer, nullable=False)
    upload_kbps: Mapped[int] = mapped_column(Integer, nullable=False)
    burst_download_kbps: Mapped[int | None] = mapped_column(Integer, nullable=True)
    burst_upload_kbps: Mapped[int | None] = mapped_column(Integer, nullable=True)
    burst_threshold_kbps: Mapped[int | None] = mapped_column(Integer, nullable=True)
    burst_time_seconds: Mapped[int | None] = mapped_column(Integer, nullable=True)
    priority: Mapped[int] = mapped_column(
        SmallInteger, nullable=False, default=8, server_default="8"
    )
    status: Mapped[str] = mapped_column(
        String(10), nullable=False, default="active", server_default="active"
    )
    notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    __table_args__ = (
        Index(
            "uq_isp_speed_groups_isp_name",
            "isp_organization_id",
            text("lower(name)"),
            unique=True,
            postgresql_where=text("deleted_at IS NULL"),
        ),
    )


class IspPackage(BaseModel):
    __tablename__ = "isp_packages"

    isp_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    speed_group_id: Mapped[uuid.UUID] = _fk("isp_speed_groups.id")
    name: Mapped[str] = mapped_column(String(150), nullable=False)
    type: Mapped[str] = mapped_column(String(10), nullable=False)
    validity_days: Mapped[int] = mapped_column(Integer, nullable=False)
    price_paise: Mapped[int] = mapped_column(BigInteger, nullable=False, default=0)
    price_includes_gst: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True, server_default=text("true")
    )
    data_cap_mb: Mapped[int | None] = mapped_column(Integer, nullable=True)
    max_devices: Mapped[int] = mapped_column(
        SmallInteger, nullable=False, default=1, server_default="1"
    )
    status: Mapped[str] = mapped_column(
        String(10), nullable=False, default="active", server_default="active"
    )
    needs_price: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default=text("false")
    )

    __table_args__ = (
        Index(
            "uq_isp_packages_isp_name",
            "isp_organization_id",
            text("lower(name)"),
            unique=True,
            postgresql_where=text("deleted_at IS NULL"),
        ),
        Index("ix_isp_packages_group", "speed_group_id"),
    )


class IspPackageMaterialization(BaseModel):
    """The existing rows a package needs inside one customer org."""

    __tablename__ = "isp_package_materializations"

    package_id: Mapped[uuid.UUID] = _fk("isp_packages.id")
    customer_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    queue_profile_id: Mapped[uuid.UUID] = _fk("queue_profiles.id")
    voucher_plan_id: Mapped[uuid.UUID] = _fk("voucher_plans.id")
    group_profile_version: Mapped[int] = mapped_column(
        Integer, nullable=False, default=1, server_default="1"
    )

    __table_args__ = (
        Index(
            "uq_isp_package_materializations_pkg_customer",
            "package_id",
            "customer_organization_id",
            unique=True,
        ),
    )


class IspCouponBatch(BaseModel):
    __tablename__ = "isp_coupon_batches"

    isp_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    package_id: Mapped[uuid.UUID] = _fk("isp_packages.id")
    customer_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    location_id: Mapped[uuid.UUID | None] = _fk("locations.id", nullable=True)
    batch_seq: Mapped[int] = mapped_column(Integer, nullable=False)
    serial_prefix: Mapped[str] = mapped_column(String(12), nullable=False)
    quantity: Mapped[int] = mapped_column(Integer, nullable=False)
    shelf_life_until: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    #: active | revoked | expired
    status: Mapped[str] = mapped_column(String(10), nullable=False)

    __table_args__ = (
        Index(
            "ix_isp_coupon_batches_isp_customer",
            "isp_organization_id",
            "customer_organization_id",
        ),
        Index(
            "uq_isp_coupon_batches_seq", "isp_organization_id", "batch_seq", unique=True
        ),
    )


class IspCouponBatchPart(BaseModel):
    """One existing ``voucher_batches`` row of an ISP coupon batch (a batch
    above 1000 codes spans several)."""

    __tablename__ = "isp_coupon_batch_parts"

    coupon_batch_id: Mapped[uuid.UUID] = _fk("isp_coupon_batches.id")
    voucher_batch_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("voucher_batches.id"),
        nullable=False,
        unique=True,
    )
    part_index: Mapped[int] = mapped_column(Integer, nullable=False)
    quantity: Mapped[int] = mapped_column(Integer, nullable=False)

    __table_args__ = (Index("ix_isp_coupon_batch_parts_batch", "coupon_batch_id"),)


class IspSubscriber(BaseModel):
    __tablename__ = "isp_subscribers"

    isp_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    customer_organization_id: Mapped[uuid.UUID] = _fk("organizations.id")
    identifier: Mapped[str] = mapped_column(String(255), nullable=False)
    display_name: Mapped[str | None] = mapped_column(String(200), nullable=True)
    package_id: Mapped[uuid.UUID | None] = _fk("isp_packages.id", nullable=True)
    speed_group_id: Mapped[uuid.UUID | None] = _fk("isp_speed_groups.id", nullable=True)
    valid_until: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    #: active | expired | disabled
    status: Mapped[str] = mapped_column(String(10), nullable=False)
    #: coupon | manual
    source: Mapped[str] = mapped_column(String(10), nullable=False)
    last_voucher_id: Mapped[uuid.UUID | None] = _fk("vouchers.id", nullable=True)
    guest_id: Mapped[uuid.UUID | None] = _fk("guests.id", nullable=True)
    # ADDENDUM_03 Part B (migration 0175): one circuit id per connection,
    # unique per ISP, immutable; contact + GST buyer fields; reminder consent.
    circuit_id: Mapped[int] = mapped_column(Integer, nullable=False)
    zone_id: Mapped[uuid.UUID | None] = _fk("isp_zones.id", nullable=True)
    first_name: Mapped[str | None] = mapped_column(String(100), nullable=True)
    last_name: Mapped[str | None] = mapped_column(String(100), nullable=True)
    phone: Mapped[str | None] = mapped_column(String(20), nullable=True)
    email: Mapped[str | None] = mapped_column(String(255), nullable=True)
    gstin: Mapped[str | None] = mapped_column(String(15), nullable=True)
    address: Mapped[str | None] = mapped_column(Text, nullable=True)
    state_code: Mapped[str | None] = mapped_column(String(2), nullable=True)
    reminder_opt_in: Mapped[dict] = mapped_column(
        JSONB,
        nullable=False,
        default=lambda: dict(DEFAULT_REMINDER_OPT_IN),
        server_default=text(
            """'{"email": true, "sms": false, "whatsapp": false}'::jsonb"""
        ),
    )

    __table_args__ = (
        Index(
            "uq_isp_subscribers_circuit",
            "isp_organization_id",
            "circuit_id",
            unique=True,
        ),
        Index(
            "uq_isp_subscribers_customer_identifier",
            "customer_organization_id",
            "identifier",
            unique=True,
            postgresql_where=text("deleted_at IS NULL"),
        ),
        Index("ix_isp_subscribers_isp", "isp_organization_id"),
        Index("ix_isp_subscribers_group", "speed_group_id"),
    )


